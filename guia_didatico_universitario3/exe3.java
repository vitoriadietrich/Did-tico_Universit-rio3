public class exe3 {

    public static int dobro(int numero) {
        return numero * 2;
    }

    public static void main(String[] args) {
        System.out.println(dobro(5));
    }
}

//dobro(5): Chama o método dobro passando o número 5 como argumento. O método pega esse 5, multiplica por 2 e devolve o resultado (10).